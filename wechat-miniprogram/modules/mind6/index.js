function computeResult(answers, qs) {
  const counts = { L1: 0, L2: 0, L3: 0, L4: 0, L5: 0, L6: 0 };
  let answered = 0;

  qs.forEach((q, i) => {
    const a = answers[i];
    if (a == null) return;
    const no = Math.max(1, Math.min(6, a + 1));
    counts['L' + no]++;
    answered++;
  });

  // 主导层级：次数最高；同分时取更高层级（成长导向，不把人往下压）
  let dom = 'L1';
  LEVEL_KEYS.forEach((k) => {
    const dk = parseInt(dom.slice(1), 10);
    const nk = parseInt(k.slice(1), 10);
    if (counts[k] > counts[dom] || (counts[k] === counts[dom] && nk > dk)) dom = k;
  });
  const no = parseInt(dom.slice(1), 10);
  const info = LEVELS[no - 1];
  const total = qs.length;
  const percent = Math.round((counts[dom] / (answered || 1)) * 100);

  return {
    levelNo: no,
    level: info.name,
    levelEn: info.en,
    type: dom,
    typeName: info.name,
    trait: `第 ${no} 层 · ${info.name}`,
    percent,
    description: info.full,
    counts,
    groups: { L1: counts.L1, L2: counts.L2, L3: counts.L3, L4: counts.L4, L5: counts.L5, L6: counts.L6 },
    raw: answered,
    total,
    totalStat: { correct: 0, wrong: 0, skipped: total - answered },
    levelColor: info.color,
  };
}

